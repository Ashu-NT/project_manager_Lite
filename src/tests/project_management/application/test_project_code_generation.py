"""Project code auto-generation + uniqueness."""

from __future__ import annotations

import pytest

from src.core.modules.project_management.application.projects.dto.commands.project_lifecycle import (
    ProjectCreateCommand,
)
from src.core.platform.common.exceptions import ValidationError


def test_create_project_autogenerates_code(services):
    services['project_query']
    project = services['project_create'].create_project(ProjectCreateCommand(name="Plant Upgrade", description=""))
    assert project.code == "PRJ-PLAN-0001"


def test_create_project_accepts_manual_code(services):
    services['project_query']
    project = services['project_create'].create_project(ProjectCreateCommand(name="Warehouse Retrofit", description="", code="prj custom 7"))
    # normalized: uppercased, unsafe runs -> '-'
    assert project.code == "PRJ-CUSTOM-7"


def test_create_project_rejects_duplicate_manual_code(services):
    services['project_query']
    services['project_create'].create_project(ProjectCreateCommand(name="Alpha", description="", code="PRJ-DUP-0001"))
    with pytest.raises(ValidationError) as exc:
        services['project_create'].create_project(ProjectCreateCommand(name="Beta", description="", code="PRJ-DUP-0001"))
    assert exc.value.code == "CODE_DUPLICATE"


def test_create_project_rejects_duplicate_manual_code_across_organizations(services):
    services['project_query']
    default_org = services["tenant_context_service"].get_active_organization()
    other_org = services["organization_commands"].create_organization(
        organization_code="PM-OPS",
        display_name="PM Operations",
        timezone_name="Europe/Berlin",
        base_currency="EUR",
    )

    services['project_create'].create_project(ProjectCreateCommand(name="Alpha", description="", code="PRJ-DUP-XORG"))
    services["tenant_context_service"].set_active_organization(other_org.id)
    try:
        with pytest.raises(ValidationError) as exc:
            services['project_create'].create_project(ProjectCreateCommand(name="Beta", description="", code="PRJ-DUP-XORG"))
        assert exc.value.code == "CODE_DUPLICATE"
    finally:
        services["tenant_context_service"].set_active_organization(default_org.id)


def test_autogenerated_codes_are_unique_and_increment(services):
    services['project_query']
    # distinct names that share the same 4-char token -> incrementing sequence
    a = services['project_create'].create_project(ProjectCreateCommand(name="Refinery One", description=""))
    b = services['project_create'].create_project(ProjectCreateCommand(name="Refining Plant", description=""))
    assert a.code == "PRJ-REFI-0001"
    assert b.code == "PRJ-REFI-0002"


def test_project_code_round_trips_through_repository(services):
    services['project_query']
    created = services['project_create'].create_project(ProjectCreateCommand(name="Bridge Works", description=""))
    reloaded = next(p for p in services['project_query'].list_projects() if p.id == created.id)
    assert reloaded.code == created.code == "PRJ-BRID-0001"
